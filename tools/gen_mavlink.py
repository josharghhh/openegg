"""Generate Kotlin MAVLink definitions from the official message_definitions XML.

Usage (from the app/ directory):
    python -I tools/gen_mavlink.py tools/mavlink-xml/common.xml CommonDialect \
        app/src/main/java/com/openegg/app/mavlink/gen/CommonDialect.kt

Follows <include> elements, emits every message (fields in declaration order,
with extension flags) plus selected enums as Kotlin constants. CRC_EXTRA is
computed here with the pymavlink algorithm and re-verified at test time.
"""
import os
import sys
import xml.etree.ElementTree as ET

TYPES = {
    "char": ("CHAR", 1), "uint8_t": ("UINT8", 1), "int8_t": ("INT8", 1),
    "uint16_t": ("UINT16", 2), "int16_t": ("INT16", 2),
    "uint32_t": ("UINT32", 4), "int32_t": ("INT32", 4), "float": ("FLOAT", 4),
    "uint64_t": ("UINT64", 8), "int64_t": ("INT64", 8), "double": ("DOUBLE", 8),
    "uint8_t_mavlink_version": ("UINT8", 1),
}

ENUMS = [
    "MAV_TYPE", "MAV_AUTOPILOT", "MAV_MODE_FLAG", "MAV_STATE", "MAV_CMD", "MAV_RESULT",
    "MAV_SEVERITY", "MAV_FRAME", "MAV_PARAM_TYPE", "MAV_MISSION_RESULT", "MAV_MISSION_TYPE",
    "MAV_LANDED_STATE", "GPS_FIX_TYPE", "MAV_SYS_STATUS_SENSOR", "MAV_BATTERY_FUNCTION",
    "MAV_BATTERY_CHARGE_STATE", "MAV_MOUNT_MODE", "MAV_VTOL_STATE", "MAV_COMPONENT",
]


def x25(data, crc=0xFFFF):
    for b in data:
        tmp = b ^ (crc & 0xFF)
        tmp = (tmp ^ (tmp << 4)) & 0xFF
        crc = ((crc >> 8) ^ (tmp << 8) ^ (tmp << 3) ^ (tmp >> 4)) & 0xFFFF
    return crc


def load(path, seen=None):
    seen = seen if seen is not None else set()
    path = os.path.abspath(path)
    if path in seen:
        return [], {}
    seen.add(path)
    root = ET.parse(path).getroot()
    messages, enums = [], {}
    for inc in root.findall("include"):
        m, e = load(os.path.join(os.path.dirname(path), inc.text.strip()), seen)
        messages += m
        for k, v in e.items():
            enums.setdefault(k, []).extend(v)
    for en in root.iter("enum"):
        vals = []
        for entry in en.findall("entry"):
            if entry.get("value") is not None:
                vals.append((entry.get("name"), int(entry.get("value"), 0)))
        enums.setdefault(en.get("name"), []).extend(vals)
    for msg in root.iter("message"):
        fields, ext = [], False
        for child in msg:
            if child.tag == "extensions":
                ext = True
            elif child.tag == "field":
                t = child.get("type")
                arr = 0
                if "[" in t:
                    t, n = t[:-1].split("[")
                    arr = int(n)
                fields.append((child.get("name"), t, arr, ext))
        messages.append((int(msg.get("id")), msg.get("name"), fields))
    return messages, enums


def crc_extra(name, fields):
    base = [f for f in fields if not f[3]]
    ordered = sorted(base, key=lambda f: -TYPES[f[1]][1])  # stable sort, like pymavlink
    crc = x25((name + " ").encode())
    for fname, t, arr, _ in ordered:
        wire_t = "uint8_t" if t == "uint8_t_mavlink_version" else t
        crc = x25((wire_t + " ").encode(), crc)
        crc = x25((fname + " ").encode(), crc)
        if arr:
            crc = x25(bytes([arr]), crc)
    return (crc & 0xFF) ^ (crc >> 8)


def kt_const(name):
    return name if not name[0].isdigit() else "_" + name


def main(xml_path, object_name, out_path):
    messages, enums = load(xml_path)
    messages.sort()
    pkg = "com.openegg.app.mavlink.gen"
    lines = [
        f"// GENERATED by tools/gen_mavlink.py from {os.path.basename(xml_path)}. Do not edit.",
        f"package {pkg}",
        "",
        "import com.openegg.app.mavlink.MavDialect",
        "import com.openegg.app.mavlink.MavField",
        "import com.openegg.app.mavlink.MavMessageDef",
        "import com.openegg.app.mavlink.MavType",
        "",
        f"object {object_name} {{",
        "    val dialect: MavDialect by lazy {",
        "        MavDialect(" + " + ".join(f"part{i}()" for i in range(0, (len(messages) + 39) // 40)) + ")",
        "    }",
        "",
    ]
    for i in range(0, len(messages), 40):
        lines.append(f"    private fun part{i // 40}(): List<MavMessageDef> = listOf(")
        for mid, name, fields in messages[i:i + 40]:
            fs = ", ".join(
                f'MavField("{n}", MavType.{TYPES[t][0]}' + (f", {a}" if a else "") + (", extension = true" if e else "") + ")"
                for n, t, a, e in fields
            )
            lines.append(f'        MavMessageDef({mid}, "{name}", listOf({fs}), {crc_extra(name, fields)}),')
        lines.append("    )")
        lines.append("")
    lines.append("}")
    lines.append("")
    for en in ENUMS:
        vals = enums.get(en)
        if not vals:
            continue
        obj = "".join(p.capitalize() for p in en.split("_"))
        lines.append(f"object {obj} {{")
        prefix = en + "_"
        done = set()
        for n, v in vals:
            short = kt_const(n[len(prefix):] if n.startswith(prefix) else n)
            if short in done:
                continue
            done.add(short)
            lit = f"{v}" if v < 2 ** 31 else f"{v}L"
            lines.append(f"    const val {short} = {lit}")
        lines.append("}")
        lines.append("")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {out_path}: {len(messages)} messages, {sum(1 for e in ENUMS if e in enums)} enums")


if __name__ == "__main__":
    main(*sys.argv[1:4])
